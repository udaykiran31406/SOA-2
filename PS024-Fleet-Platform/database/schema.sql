CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(60) NOT NULL,
    user_role VARCHAR(20) NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_number VARCHAR(20) NOT NULL,
    make VARCHAR(100) NOT NULL,
    model VARCHAR(100) NOT NULL,
    vehicle_year SMALLINT NOT NULL,
    status VARCHAR(32) NOT NULL,
    assigned_driver VARCHAR(150),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_vehicles_registration_number UNIQUE (registration_number),
    CONSTRAINT chk_vehicles_year CHECK (vehicle_year BETWEEN 1886 AND 2100),
    CONSTRAINT chk_vehicles_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'UNDER_MAINTENANCE'))
);

CREATE TABLE IF NOT EXISTS maintenance_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL,
    service_type VARCHAR(32) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    scheduled_date DATE NOT NULL,
    completed_date DATE,
    cost DECIMAL(10, 2) NOT NULL,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_maintenance_vehicle_id CHECK (vehicle_id > 0),
    CONSTRAINT chk_maintenance_service_type CHECK (
        service_type IN ('PREVENTIVE', 'REPAIR', 'INSPECTION', 'OIL_CHANGE', 'TIRE_SERVICE', 'OTHER')
    ),
    CONSTRAINT chk_maintenance_status CHECK (
        status IN ('SCHEDULED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')
    ),
    CONSTRAINT chk_maintenance_cost CHECK (cost >= 0),
    CONSTRAINT chk_maintenance_dates CHECK (
        (completed_date IS NULL OR completed_date >= scheduled_date)
        AND (status <> 'COMPLETED' OR completed_date IS NOT NULL)
    )
);
